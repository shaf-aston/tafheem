/**
 * Draws src/lib/colloquial/dialectsPreview.json: a display-only trim of every
 * spoken dialect in backend/data/colloquial/dialects.json, for the landing
 * page's Dialects section (landing/Dialects.jsx). The landing page has no
 * query client and no live API call, so it cannot read the real catalogue
 * (api.js colloquialQuery); this keeps only the fields CountryMap/CountryIcons
 * draw (key, label, arabic, where, countries, cities), in the backend file's
 * own `order`, and leaves Fusha out since it is Modern Standard Arabic taught
 * across every country, not one of the picked-a-country dialects this section
 * is showing off.
 *
 * Run once; the output is committed and the app needs none of this:
 *
 *   node scripts/dialectsPreview.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const { dialects } = JSON.parse(readFileSync(new URL('../../backend/data/colloquial/dialects.json', import.meta.url), 'utf8'))

const out = dialects
  .filter((d) => d.key !== 'fusha')
  .sort((a, b) => a.order - b.order)
  .map(({ key, label, arabic, where, countries, cities }) => ({ key, label, arabic, where, countries, cities }))

const file = new URL('../src/lib/colloquial/dialectsPreview.json', import.meta.url)
writeFileSync(file, JSON.stringify({
  _about: 'A display-only trim of backend/data/colloquial/dialects.json\'s `dialects` list, for the landing page\'s Dialects section (landing/Dialects.jsx). The landing page has no query client and no live API call, so it cannot read the real catalogue (api.js colloquialQuery); this keeps only the fields CountryMap/CountryIcons draw (key, label, arabic, where, countries, cities), in the backend file\'s own `order`, and leaves Fusha out since it is Modern Standard Arabic taught across every country, not one of the picked-a-country dialects this section is showing off. Generated by scripts/dialectsPreview.mjs from backend/data/colloquial/dialects.json. Do not edit by hand.',
  dialects: out,
}) + '\n')
console.log(out.length, 'dialects,', readFileSync(file).length, 'bytes')
